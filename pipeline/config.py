def _current_season(today=None):
    if today is None:
        override = os.environ.get("IVY_TODAY")  # YYYY-MM-DD: for tests, or to see what a run in September would do
        today = date.fromisoformat(override) if override else date.today()
    return today.year if today.month >= SEASON_STARTS_IN_MONTH else today.year - 1


